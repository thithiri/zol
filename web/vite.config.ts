import { existsSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { defineConfig } from "vite";

/** The generated docs pages (every .html under docs/), as build inputs: docs/reference/ledger.html -> "docs/reference/ledger". */
function docPages(): Record<string, string> {
  const root = fileURLToPath(new URL(".", import.meta.url));
  const dir = join(root, "docs");
  if (!existsSync(dir)) return {};
  const walk = (d: string): string[] => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : f.endsWith(".html") ? [join(d, f)] : []));
  return Object.fromEntries(walk(dir).map((f) => [relative(root, f).replace(/\.html$/, ""), f]));
}

export default defineConfig({
  // src/wire.ts is a symlink to crates/zol-wire/ts/wire.ts.
  server: { fs: { allow: [".."] } },
  // Browser bundles get an empty `process.env`. Scripts run with vite-node (house/, examples/,
  // scripts/) need the real one: their settings come from environment variables.
  define: process.argv.some((a) => /vite-node/.test(a)) ? {} : { "process.env": {} },
  // Pages: the landing page (/), the games page (deposit, withdraw, the games), the coin flip
  // and Up/Down (the three from coinflip.html, see scripts/pages.py), the auction, the original
  // two-player table, and the developer docs (docs/, generated by scripts/docs.mjs).
  build: { rollupOptions: { input: { main: "index.html", play: "play.html", coinflip: "coinflip.html", updown: "updown.html", auction: "auction.html", twoplayer: "two-player.html", ...docPages() } } },
  test: { include: ["test/**/*.test.ts"] },
} as any);
